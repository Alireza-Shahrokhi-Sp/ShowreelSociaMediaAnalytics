    '\n'
    'pb_cfg = types.GenerateContentConfig(\n'
    '    temperature=0.0, top_p=1.0, max_output_tokens=8192,\n'
    '    response_mime_type="application/json",\n'
    '    thinking_config=types.ThinkingConfig(thinking_budget=4096),\n'
    ')\n'
    'print(f"Labelling {len(_real_summaries)} real clusters via {MODEL_STAGE3_NAMING} (noise excluded) ...")\n'
    'pb_resp = client.models.generate_content(model=MODEL_STAGE3_NAMING, contents=pb_prompt, config=pb_cfg)\n'
    '\n'
    '_pb_text = strip_fences(pb_resp.text or "")\n'
    'try:\n'
    '    pb_macro_personas = json.loads(_pb_text)\n'
    'except Exception as e:\n'
    '    print("Could not parse LLM output:", str(e)[:120], "\\n", _pb_text[:400])\n'
    '    pb_macro_personas = []\n'
    '\n'
    '_keys = ["codename", "label", "description", "quantitative_signals", "example_comments", "labeling_rationale"]\n'
    'pb_macro_personas = [{k: p.get(k, "" if k in ("codename","label","description","labeling_rationale") else [])\n'
    '                      for k in _keys}\n'
    '                     for p in pb_macro_personas if isinstance(p, dict)][:TARGET_PERSONAS]\n'
    '\n'
    '# Append a synthetic NOISE_UNCLASSIFIED entry for the noise cluster (not LLM-labelled).\n'
    'if _noise_summary is not None:\n'
    '    _noise_persona = {\n'
    '        "codename": "NOISE_UNCLASSIFIED",\n'
    '        "label": "Unclassified / Noise",\n'
    '        "description": (\n'
    '            f"HDBSCAN could not assign {_noise_summary[\'n_users\']:,} users "\n'
    '            f"({_noise_summary[\'pct_audience\']}% of audience) to any dense cluster. "\n'
    '            "These are low-cohesion, behaviorally scattered users who do not fit any dominant pattern."\n'
    '        ),\n'
    '        "quantitative_signals": [\n'
    '            f"n_users={_noise_summary[\'n_users\']:,}",\n'
    '            f"pct_audience={_noise_summary[\'pct_audience\']}%",\n'
    '            "No dominant behavioural pattern detected by HDBSCAN",\n'
    '        ],\n'
    '        "example_comments": _noise_summary["sample_comments"][:3],\n'
    '        "labeling_rationale": "Assigned programmatically — HDBSCAN cluster_id=-1 (noise points)."\n'
    '    }\n'
    '    pb_macro_personas.append(_noise_persona)\n'
    '\n'
    'print(f"\\n{len(pb_macro_personas)} personas from Pathway B:")\n'
    'for p in pb_macro_personas:\n'
    '    is_noise = p["codename"] == "NOISE_UNCLASSIFIED"\n'
    '    tag = " [NOISE]" if is_noise else ""\n'
    '    print(f"   {str(p[\'codename\']):<30}{tag}  | {p[\'label\']}")\n'
    '    if not is_noise and p.get("labeling_rationale"):\n'
    '        print(f"      rationale: {p[\'labeling_rationale\'][:120]}")\n'
    '\n'
    'import os\n'
    'if os.path.exists(TAXONOMY_JSON_PATH):\n'
    '    data = json.load(open(TAXONOMY_JSON_PATH, encoding="utf-8"))\n'
    'else:\n'
    '    data = {"status": "PENDING_HUMAN_REVIEW", "raw_candidates": []}\n'

    '    "For each persona output exactly these 6 keys:\\n"\n'
    '    "  codename (UPPER_SNAKE_CASE),\\n"\n'
    '    "  label (short Title Case, 2-4 words),\\n"\n'
    '    "  description (1-2 sentences — who they are and what drives their engagement),\\n"\n'

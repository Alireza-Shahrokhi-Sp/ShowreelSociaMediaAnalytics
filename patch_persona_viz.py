# ── Patch 3: pb-sentiment-persona-plots — expand with toxicity charts ────
NEW_SENT_PLOTS_SRC = (
    'import pandas as pd\n'
    'import matplotlib.pyplot as plt\n'
    'import matplotlib.ticker as mticker\n'
    'import json, os\n'
    '\n'
    '# ── load data ──────────────────────────────────────────────────────────────\n'
    '_pb   = pd.read_parquet(f"{LOCAL_DIR}/pathway_b_assignments_{PLATFORM}.parquet")\n'
    '_pb["author_id"] = _pb["author_id"].astype(str)\n'
    '\n'
    '_sent_raw = pd.read_parquet(SENTIMENT_PATH)\n'
    '_sent_raw["author_id"] = _sent_raw["author_id"].astype(str) if "author_id" in _sent_raw.columns else _sent_raw.get("author_id", pd.Series(dtype=str))\n'
    '\n'
    '# dominant sentiment category per user\n'
    '_dom_sent = (_sent_raw.groupby("author_id")[SENTIMENT_STRATA_COL]\n'
    '              .agg(lambda x: x.value_counts().idxmax())\n'
    '              .reset_index()\n'
    '              .rename(columns={SENTIMENT_STRATA_COL: "dominant_sentiment"}))\n'
    '\n'
    '# dominant toxicity level per user (none/mild/severe/spam_promo)\n'
    '_dom_tox = None\n'
    'if "toxicity" in _sent_raw.columns:\n'
    '    _dom_tox = (_sent_raw.groupby("author_id")["toxicity"]\n'
    '                .agg(lambda x: x.value_counts().idxmax())\n'
    '                .reset_index()\n'
    '                .rename(columns={"toxicity": "dominant_toxicity"}))\n'
    '\n'
    '_cmap = json.load(open(CLUSTER_PERSONA_MAP_PATH, encoding="utf-8"))\n'
    '_cmap_int = {int(k): v for k, v in _cmap.items()}\n'
    '\n'
    '_df = (_pb.merge(_dom_sent, on="author_id", how="left"))\n'
    'if _dom_tox is not None:\n'
    '    _df = _df.merge(_dom_tox, on="author_id", how="left")\n'
    'else:\n'
    '    _df["dominant_toxicity"] = "unknown"\n'
    '\n'
    '_df["persona"] = _df["macro_cluster"].map(_cmap_int).fillna("UNKNOWN")\n'
    '_df_real = _df[_df["macro_cluster"] != -1].copy()  # exclude NOISE from charts\n'
    '_df_noise = _df[_df["macro_cluster"] == -1].copy()\n'
    '\n'
    'os.makedirs(f"{LOCAL_DIR}/figs", exist_ok=True)\n'
    '\n'
    'SENT_ORDER  = ["negative", "neutral", "positive"]\n'
    'SENT_COLORS = {"negative": "#d62728", "neutral": "#aec7e8", "positive": "#2ca02c"}\n'
    'TOX_ORDER   = ["none", "mild", "severe", "spam_promo"]\n'
    'TOX_COLORS  = {"none": "#9ecae1", "mild": "#fdae6b", "severe": "#d62728", "spam_promo": "#756bb1"}\n'
    '\n'
    '# ── figure 1: persona distribution for NEGATIVE users ─────────────────────\n'
    'fig1, ax1 = plt.subplots(figsize=(10, 5))\n'
    'neg = (_df_real[_df_real["dominant_sentiment"] == "negative"]\n'
    '       .groupby("persona").size().sort_values(ascending=False))\n'
    'ax1.bar(neg.index, neg.values, color=SENT_COLORS["negative"], alpha=0.85)\n'
    'ax1.set_title("Persona Distribution — Negative-Dominant Users", fontsize=13, pad=10)\n'
    'ax1.set_xlabel("Persona")\n'
    'ax1.set_ylabel("User count")\n'
    'ax1.yaxis.set_major_locator(mticker.MaxNLocator(integer=True))\n'
    'plt.xticks(rotation=35, ha="right", fontsize=9)\n'
    'plt.tight_layout()\n'
    'plt.savefig(f"{LOCAL_DIR}/figs/persona_negative_users.png", dpi=150)\n'
    'plt.show()\n'
    'print("saved persona_negative_users.png")\n'
    '\n'
    '# ── figure 2: stacked 100% bar — sentiment mix per persona ────────────────\n'
    '_ct_sent = (_df_real.dropna(subset=["dominant_sentiment"])\n'
    '            .groupby(["persona", "dominant_sentiment"])\n'
    '            .size().unstack(fill_value=0)\n'
    '            .reindex(columns=[c for c in SENT_ORDER if c in _df_real["dominant_sentiment"].unique()], fill_value=0))\n'
    '_pct_sent = _ct_sent.div(_ct_sent.sum(axis=1), axis=0) * 100\n'
    '_pct_sent = _pct_sent.loc[_ct_sent.sum(axis=1).sort_values(ascending=False).index]\n'
    '\n'
    'fig2, ax2 = plt.subplots(figsize=(11, 5))\n'
    'bottom = pd.Series(0.0, index=_pct_sent.index)\n'
    'for sent in [c for c in SENT_ORDER if c in _pct_sent.columns]:\n'
    '    vals = _pct_sent[sent]\n'
    '    ax2.bar(_pct_sent.index, vals, bottom=bottom,\n'
    '            label=sent.capitalize(), color=SENT_COLORS[sent], alpha=0.88)\n'
    '    bottom += vals\n'
    'ax2.set_title("Sentiment Mix per Persona (% of persona users)", fontsize=13, pad=10)\n'
    'ax2.set_xlabel("Persona (sorted by total users)")\n'
    'ax2.set_ylabel("% of users")\n'
    'ax2.set_ylim(0, 100)\n'
    'ax2.legend(title="Dominant sentiment", loc="upper right", fontsize=9)\n'
    'plt.xticks(rotation=35, ha="right", fontsize=9)\n'
    'plt.tight_layout()\n'
    'plt.savefig(f"{LOCAL_DIR}/figs/persona_sentiment_mix.png", dpi=150)\n'
    'plt.show()\n'
    'print("saved persona_sentiment_mix.png")\n'
    '\n'
    '# ── figure 3: heatmap — negative-user share (%) per persona ───────────────\n'
    '_neg_share = (_ct_sent.get("negative", pd.Series(0, index=_ct_sent.index))\n'
    '              / _ct_sent.sum(axis=1) * 100).sort_values(ascending=False)\n'
    '\n'
    'fig3, ax3 = plt.subplots(figsize=(10, 3))\n'
    'im = ax3.imshow(_neg_share.values.reshape(1, -1), aspect="auto",\n'
    '                cmap="Reds", vmin=0, vmax=max(_neg_share.max(), 5))\n'
    'ax3.set_xticks(range(len(_neg_share)))\n'
    'ax3.set_xticklabels(_neg_share.index, rotation=35, ha="right", fontsize=9)\n'
    'ax3.set_yticks([])\n'
    'plt.colorbar(im, ax=ax3, orientation="horizontal", pad=0.35,\n'
    '             label="% negative-dominant users")\n'
    'ax3.set_title("Negative-User Concentration per Persona", fontsize=12, pad=8)\n'
    'plt.tight_layout()\n'
    'plt.savefig(f"{LOCAL_DIR}/figs/persona_negative_heatmap.png", dpi=150)\n'
    'plt.show()\n'
    'print("saved persona_negative_heatmap.png")\n'
    '\n'
    '# ── figure 4: stacked 100% bar — toxicity mix per persona ─────────────────\n'
    'if "dominant_toxicity" in _df_real.columns and _df_real["dominant_toxicity"].notna().any():\n'
    '    _ct_tox = (_df_real.dropna(subset=["dominant_toxicity"])\n'
    '               .groupby(["persona", "dominant_toxicity"])\n'
    '               .size().unstack(fill_value=0)\n'
    '               .reindex(columns=[c for c in TOX_ORDER if c in _df_real["dominant_toxicity"].unique()], fill_value=0))\n'
    '    _pct_tox = _ct_tox.div(_ct_tox.sum(axis=1), axis=0) * 100\n'
    '    _pct_tox = _pct_tox.loc[_ct_tox.sum(axis=1).sort_values(ascending=False).index]\n'
    '\n'
    '    fig4, ax4 = plt.subplots(figsize=(11, 5))\n'
    '    bottom4 = pd.Series(0.0, index=_pct_tox.index)\n'
    '    for tox in [c for c in TOX_ORDER if c in _pct_tox.columns]:\n'
    '        ax4.bar(_pct_tox.index, _pct_tox[tox], bottom=bottom4,\n'
    '                label=tox.replace("_", " ").capitalize(),\n'
    '                color=TOX_COLORS.get(tox, "#888888"), alpha=0.88)\n'
    '        bottom4 += _pct_tox[tox]\n'
    '    ax4.set_title("Toxicity Mix per Persona (% of persona users)", fontsize=13, pad=10)\n'
    '    ax4.set_xlabel("Persona (sorted by total users)")\n'
    '    ax4.set_ylabel("% of users")\n'
    '    ax4.set_ylim(0, 100)\n'
    '    ax4.legend(title="Dominant toxicity", loc="upper right", fontsize=9)\n'
    '    plt.xticks(rotation=35, ha="right", fontsize=9)\n'
    '    plt.tight_layout()\n'
    '    plt.savefig(f"{LOCAL_DIR}/figs/persona_toxicity_mix.png", dpi=150)\n'
    '    plt.show()\n'
    '    print("saved persona_toxicity_mix.png")\n'
    '\n'
    '    # ── figure 5: toxicity rate heatmap ──────────────────────────────────────\n'
    '    _tox_rate = ((_ct_tox.get("mild", 0) + _ct_tox.get("severe", 0))\n'
    '                 / _ct_tox.sum(axis=1) * 100).sort_values(ascending=False)\n'
    '    fig5, ax5 = plt.subplots(figsize=(10, 3))\n'
    '    im5 = ax5.imshow(_tox_rate.values.reshape(1, -1), aspect="auto",\n'
    '                     cmap="Oranges", vmin=0, vmax=max(_tox_rate.max(), 5))\n'
    '    ax5.set_xticks(range(len(_tox_rate)))\n'
    '    ax5.set_xticklabels(_tox_rate.index, rotation=35, ha="right", fontsize=9)\n'
    '    ax5.set_yticks([])\n'
    '    plt.colorbar(im5, ax=ax5, orientation="horizontal", pad=0.35,\n'
    '                 label="% toxic (mild+severe) users")\n'
    '    ax5.set_title("Toxic-User Concentration per Persona", fontsize=12, pad=8)\n'
    '    plt.tight_layout()\n'
    '    plt.savefig(f"{LOCAL_DIR}/figs/persona_toxic_heatmap.png", dpi=150)\n'
    '    plt.show()\n'
    '    print("saved persona_toxic_heatmap.png")\n'
    'else:\n'
    '    print("No toxicity column found in sentiment parquet — skipping toxicity charts.")\n'
    '\n'
    '# ── summary table ──────────────────────────────────────────────────────────\n'
    'print("\\nPersona  |  total  |  neg%  |  pos%  |  toxic%")\n'
    'print("-" * 60)\n'
    'for p, row in _pct_sent.iterrows():\n'
    '    total = int(_ct_sent.loc[p].sum())\n'
    '    tox_pct = 0.0\n'
    '    if "dominant_toxicity" in _df_real.columns and p in _ct_tox.index:\n'
    '        tox_pct = float((_ct_tox.get("mild", pd.Series(0, index=_ct_tox.index)).loc[p]\n'
    '                         + _ct_tox.get("severe", pd.Series(0, index=_ct_tox.index)).loc[p])\n'
    '                        / _ct_tox.loc[p].sum() * 100)\n'
    '    neg_pct = row.get("negative", 0)\n'
    '    pos_pct = row.get("positive", 0)\n'
    '    print(f"  {p:<32s}  {total:5d}   {neg_pct:5.1f}%   {pos_pct:5.1f}%   {tox_pct:5.1f}%")\n'
)

compile(NEW_SENT_PLOTS_SRC, 'pb-sentiment-persona-plots', 'exec')

# ── Patch 1: pb-config — add missing constants ────────────────────────────
PB_CONFIG_OLD = 'PATHWAY_B_TARGET_CLUSTERS = 12\nprint("Pathway B config loaded (target ~", PATHWAY_B_TARGET_CLUSTERS, "clusters).")'

PB_CONFIG_NEW = (
    'PATHWAY_B_TARGET_CLUSTERS = 12\n'
    'TARGET_PERSONAS            = PATHWAY_B_TARGET_CLUSTERS\n'
    'STRATIFY_BY_SENTIMENT      = True\n'
    'SENTIMENT_STRATA_COL       = "sentiment"   # column in sentiment_<platform>.parquet to stratify on\n'
    'CLUSTER_PERSONA_MAP_PATH   = f"{LOCAL_DIR}/cluster_persona_map_{PLATFORM}.json"\n'
    'print("Pathway B config loaded (target ~", PATHWAY_B_TARGET_CLUSTERS, "clusters).")'
)

for cell in nb['cells']:
    if cell['id'] == 'pb-config':
        src = ''.join(cell['source'])
        assert PB_CONFIG_OLD in src, f"pb-config pattern not found. src=\n{src}"
        src = src.replace(PB_CONFIG_OLD, PB_CONFIG_NEW)
        compile(src, 'pb-config', 'exec')
        lines = src.split('\n')
        cell['source'] = [l + '\n' for l in lines[:-1]] + ([lines[-1]] if lines[-1] else [])
        print('patched pb-config')
        break

